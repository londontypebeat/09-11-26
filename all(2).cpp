#include <iostream>
#include <algorithm>  // sort
using namespace std;

int a[100];  // стоимости растений (N ≤ 100 по условию)

int main() {
    int n, k, l;
    cin >> n >> k >> l;              // N растений, K в букете, L — лимит одинаковых
    for (int i = 0; i < n; i++)
        cin >> a[i];                 // читаем стоимости

    sort(a, a + n);  // сортируем по возрастанию — самые дорогие окажутся в конце

    long long sum = 0;             // итоговая стоимость букета
    int taken = 0;                 // сколько растений уже положили в букет
    int used = 0;                  // сколько растений текущей стоимости уже взяли
    int prev = 1000000001;         // «заглушка», заведомо не равная ни одной стоимости

    // идём с самого дорогого к дешёвым, пока не набрали K штук
    for (int i = n - 1; i >= 0 && taken < k; i--) {
        if (a[i] != prev) {        // встретили новую стоимость —
            prev = a[i];           // запоминаем её и
            used = 0;              // обнуляем счётчик одинаковых
        }
        if (used == l) continue;   // лимит L на эту стоимость исчерпан — пропускаем
        used++;                    // берём растение
        taken++;
        sum += a[i];
    }

    cout << sum << "\n";           // максимальная стоимость букета
}
