#include <iostream>   // cin, cout — ввод и вывод
#include <sstream>    // stringstream — чтобы разбирать числа из строки
using namespace std;  // чтобы не писать std:: перед каждым именем

// Таблицы 100x100 с запасом:
long long a[100][100];    // сама карта: баллы клеток
long long dp[100][100];   // dp[i][j] = максимум баллов, который можно собрать, дойдя до клетки (i, j)

int main() {
    int n = 0, m = 0;     // число строк и столбцов — узнаем из ввода, не спрашиваем у пользователя
    string line;          // буфер для очередной строки ввода

    // --- ШАГ 1. ЧТЕНИЕ КАРТЫ ---
    // Читаем строки, пока ввод не закончится. Каждая непустая строка — ряд карты.
    while (getline(cin, line)) {
        stringstream ss(line);  // «лента» из текста строки — из нее достаем числа
        long long x;            // очередное прочитанное число
        int j = 0;              // столбец в текущей строке

        while (ss >> x)         // достаем числа по одному, пока они есть в строке
            a[n][j++] = x;      // кладем в таблицу и сдвигаемся вправо

        if (j) {                // если в строке были числа (не пустая строка)...
            m = j;              // ...запоминаем число столбцов (из любой строки, они равны)...
            n++;                // ...и считаем эту строку
        }
    }

    // --- ШАГ 2. ДИНАМИКА: ЗАПОЛНЯЕМ ТАБЛИЦУ dp ---
    // Идем сверху вниз, слева направо: тогда соседи сверху и слева уже посчитаны.
    for (int i = 0; i < n; i++)
        for (int j = 0; j < m; j++) {
            // Сначала база: лучший путь до клетки содержит как минимум ее собственный балл.
            // Позже прибавим лучший путь ДО этой клетки — сверху или слева.
            dp[i][j] = a[i][j];

            if (i == 0 && j > 0)          // первая строка: сверху стены, прийти можно только слева
                dp[i][j] += dp[i][j - 1];
            if (j == 0 && i > 0)          // первый столбец: слева стены, прийти можно только сверху
                dp[i][j] += dp[i - 1][j];
            if (i > 0 && j > 0)           // обычная клетка: два варианта, берем лучший
                dp[i][j] += max(dp[i - 1][j], dp[i][j - 1]);

            // В углу (0,0) ни одно условие не сработало: dp[0][0] = a[0][0] — это старт.
        }
    // Теперь dp[n-1][m-1] — максимальная сумма по всему маршруту.

    // --- ШАГ 3. ВОССТАНОВЛЕНИЕ ПУТИ (с конца) ---
    // Идем от финиша к старту: на каждом шаге смотрим, через какого соседа
    // «прошел» максимум. Так разматываем оптимальный маршрут в обратную сторону.
    int x[10000], y[10000]; // сюда записываем координаты пути
    int len = 0;            // сколько клеток уже записали
    int i = n - 1, j = m - 1; // стартуем с правого нижнего угла

    while (i > 0 || j > 0) {  // крутим, пока не дошли до старта (0,0)
        x[len] = i;           // запоминаем текущую клетку
        y[len] = j;
        len++;

        // Выбираем, откуда «пришли» в эту клетку:
        //   i > 0                 — клетка сверху вообще существует;
        //   j == 0                — слева клетки нет, значит пришли только сверху;
        //   dp[i-1][j] >= dp[i][j-1] — верхний сосед не хуже левого, путь шел через него.
        if (i > 0 && (j == 0 || dp[i - 1][j] >= dp[i][j - 1]))
            i--;              // шагаем вверх
        else
            j--;              // шагаем влево
    }

    // Цикл остановился на старте, но саму клетку (0,0) внутри цикла мы не записали — дописываем.
    x[len] = 0;
    y[len] = 0;
    len++;

    // --- ШАГ 4. ПЕЧАТЬ ---
    // Путь собран задом наперёд (финиш -> старт), поэтому печатаем массив с конца:
    // k идет от len-1 до 0, и на экране порядок получается «старт -> финиш».
    for (int k = len - 1; k >= 0; k--)
        cout << x[k] << " " << y[k] << "\n";  // координаты: строка и столбец

    return 0; // программа закончилась успешно
}
