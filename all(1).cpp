#include <iostream>
#include <algorithm>  // sort
using namespace std;

const int INF = 1000000000;

int a[1000];          // калорийности пирожков
int dp[1001][1001];   // dp[i][j] = минимально возможная «худшая» разница,
                      //           если первые i пирожков разложили ровно по j дням

int main() {
    int n, d;
    cin >> n >> d;               // первое число N, второе число D
    for (int i = 0; i < n; i++)  // дальше N калорийностей
        cin >> a[i];

    sort(a, a + n);  // сортируем: в день выгодно брать пирожки с близкими калориями

    // вся таблица помечена «так разложить нельзя»
    for (int i = 0; i <= n; i++)
        for (int j = 0; j <= d; j++)
            dp[i][j] = INF;

    dp[0][0] = 0;  // база: 0 пирожков по 0 дням — разложения нет, разница 0

    for (int i = 1; i <= n; i++)          // сколько пирожков уже разобрали
        for (int j = 1; j <= d; j++)      // сколько дней уже заняли
            // последний (j-й) день забрал пирожки с номерами k..i-1,
            // дни 1..j-1 до этого разобрали первые k штук
            for (int k = j - 1; k < i; k++)
                if (dp[k][j - 1] != INF) {            // такое разложение существует
                    int day = a[i - 1] - a[k];        // разница внутри j-го дня
                    int val = max(dp[k][j - 1], day); // худший день среди всех j
                    if (val < dp[i][j]) dp[i][j] = val;
                }

    cout << dp[n][d] << "\n";  // ответ: минимальная разница в худшем дне
}

